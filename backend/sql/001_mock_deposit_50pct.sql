-- BOOKIFY: DEVELOPMENT-ONLY mock deposit checkout.
-- Execute once in Supabase SQL Editor AFTER taking a database backup.
-- Does NOT alter existing reservation columns or replace existing payment functions.
-- Review the actual reservation-status CHECK/ENUM before running: this integration expects CONFIRMED.

CREATE TABLE IF NOT EXISTS public.bookify_mock_deposit_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT NOT NULL UNIQUE REFERENCES public.reservations(id) ON DELETE RESTRICT,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    currency TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'SUCCEEDED' CHECK (status = 'SUCCEEDED'),
    method TEXT NOT NULL DEFAULT 'MOCK' CHECK (method = 'MOCK'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_bookify_mock_deposit_user
    ON public.bookify_mock_deposit_payments(user_id, created_at DESC);
ALTER TABLE public.bookify_mock_deposit_payments ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.bookify_mock_deposit_payments FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.bookify_complete_mock_deposit(
    p_reservation_id BIGINT,
    p_user_id BIGINT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
    r public.reservations%ROWTYPE;
    p public.bookify_mock_deposit_payments%ROWTYPE;
    expected_deposit NUMERIC(12,2);
BEGIN
    IF p_reservation_id IS NULL OR p_reservation_id < 1
       OR p_user_id IS NULL OR p_user_id < 1 THEN
       RAISE EXCEPTION 'Invalid reservation or user ID' USING ERRCODE = '22023';
    END IF;

    -- Row lock makes concurrent requests safe; entire function is a single DB transaction.
    SELECT * INTO r FROM public.reservations WHERE id = p_reservation_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Reservation not found' USING ERRCODE = 'P0002';
    END IF;
    IF r.user_id IS DISTINCT FROM p_user_id THEN
        RAISE EXCEPTION 'This reservation does not belong to your account' USING ERRCODE = '42501';
    END IF;

    -- Repeated submit/retry is idempotent only for a payment created by this module.
    SELECT * INTO p FROM public.bookify_mock_deposit_payments
      WHERE reservation_id = r.id;
    IF FOUND THEN
        IF r.status <> 'CONFIRMED' THEN
            RAISE EXCEPTION 'Payment record and reservation state are inconsistent' USING ERRCODE = 'P0001';
        END IF;
        RETURN jsonb_build_object(
            'success', TRUE, 'already_paid', TRUE,
            'reservation', jsonb_build_object('id', r.id, 'status', r.status,
                'total_amount', r.total_amount, 'deposit_amount', r.deposit_amount,
                'balance_amount', r.balance_amount, 'currency', r.currency,
                'starts_at', r.starts_at),
            'payment', jsonb_build_object('id', p.id, 'amount', p.amount,
                'currency', p.currency, 'status', p.status, 'method', 'MOCK', 'created_at', p.created_at)
        );
    END IF;

    IF r.status <> 'PENDING_PAYMENT' THEN
        RAISE EXCEPTION 'Only reservations awaiting payment can be confirmed' USING ERRCODE = 'P0001';
    END IF;
    IF r.payment_expires_at IS NULL OR r.payment_expires_at <= now() THEN
        RAISE EXCEPTION 'Payment deadline has expired' USING ERRCODE = 'P0001';
    END IF;
    IF r.starts_at <= now() THEN
        RAISE EXCEPTION 'Cannot confirm an appointment in the past' USING ERRCODE = 'P0001';
    END IF;
    expected_deposit := round((r.total_amount::numeric * 0.5), 2);
    IF expected_deposit <= 0 OR r.deposit_amount IS DISTINCT FROM expected_deposit
        OR (r.balance_amount + r.deposit_amount) IS DISTINCT FROM r.total_amount THEN
        RAISE EXCEPTION 'Stored deposit is not 50 percent of the service price' USING ERRCODE = 'P0001';
    END IF;

    INSERT INTO public.bookify_mock_deposit_payments (reservation_id, user_id, amount, currency)
    VALUES (r.id, p_user_id, r.deposit_amount, r.currency)
    RETURNING * INTO p;

    -- Existing DB constraints/triggers still apply; any failure rolls back BOTH operations.
    UPDATE public.reservations
       SET status = 'CONFIRMED', updated_at = now()
     WHERE id = r.id AND user_id = p_user_id AND status = 'PENDING_PAYMENT'
    RETURNING * INTO r;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Reservation state changed before confirmation' USING ERRCODE = 'P0001';
    END IF;

    RETURN jsonb_build_object(
        'success', TRUE, 'already_paid', FALSE,
        'reservation', jsonb_build_object('id', r.id, 'status', r.status,
            'total_amount', r.total_amount, 'deposit_amount', r.deposit_amount,
            'balance_amount', r.balance_amount, 'currency', r.currency,
            'starts_at', r.starts_at),
        'payment', jsonb_build_object('id', p.id, 'amount', p.amount,
            'currency', p.currency, 'status', p.status, 'method', 'MOCK', 'created_at', p.created_at)
    );
END;
$$;

REVOKE ALL ON FUNCTION public.bookify_complete_mock_deposit(BIGINT, BIGINT) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.bookify_complete_mock_deposit(BIGINT, BIGINT) TO service_role;

