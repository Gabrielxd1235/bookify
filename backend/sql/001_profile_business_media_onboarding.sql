-- BOOKIFY additive migration, PostgreSQL / Supabase SQL Editor.
-- Read PREPARACION_ES.md and make a database backup before applying.
-- Assumes existing public.users, categories, businesses and their numeric IDs.
-- No destructive changes to the six original project tables.

BEGIN;

ALTER TABLE public.users
  ADD COLUMN IF NOT EXISTS phone text,
  ADD COLUMN IF NOT EXISTS avatar_path text,
  ADD COLUMN IF NOT EXISTS password_changed_at timestamptz;

ALTER TABLE public.businesses
  ADD COLUMN IF NOT EXISTS logo_path text,
  ADD COLUMN IF NOT EXISTS cover_path text;

CREATE TABLE IF NOT EXISTS public.business_images (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id bigint NOT NULL REFERENCES public.businesses(id) ON DELETE CASCADE,
  storage_path text NOT NULL UNIQUE,
  caption text,
  sort_order integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT business_images_caption_len CHECK (caption IS NULL OR char_length(caption) <= 180),
  CONSTRAINT business_images_sort_order_range CHECK (sort_order BETWEEN 0 AND 1000)
);
CREATE INDEX IF NOT EXISTS idx_business_images_business_id
  ON public.business_images(business_id, sort_order, created_at);

CREATE TABLE IF NOT EXISTS public.business_owner_applications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  category_id bigint NOT NULL REFERENCES public.categories(id),
  business_name text NOT NULL,
  description text,
  address text NOT NULL,
  phone text,
  logo_path text,
  cover_path text,
  status text NOT NULL DEFAULT 'PENDING',
  admin_note text,
  reviewed_by bigint REFERENCES public.users(id),
  reviewed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT owner_application_status_allowed CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
  CONSTRAINT owner_application_name_len CHECK (char_length(btrim(business_name)) BETWEEN 3 AND 150),
  CONSTRAINT owner_application_address_len CHECK (char_length(btrim(address)) BETWEEN 5 AND 300),
  CONSTRAINT owner_application_description_len CHECK (description IS NULL OR char_length(description) <= 1000),
  CONSTRAINT owner_application_phone_len CHECK (phone IS NULL OR char_length(phone) <= 30)
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_owner_applications_single_pending
  ON public.business_owner_applications(user_id)
  WHERE status = 'PENDING';
CREATE INDEX IF NOT EXISTS idx_owner_applications_admin_queue
  ON public.business_owner_applications(status, created_at DESC);

-- Existing backend uses a server-only Supabase secret. Client-side roles
-- must not be able to bypass the API or modify these review records.
-- Ensure the private server role can use the new tables and identity sequences.
GRANT SELECT, INSERT, UPDATE, DELETE ON public.business_images TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.business_owner_applications TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.business_images_id_seq TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.business_owner_applications_id_seq TO service_role;

ALTER TABLE public.business_images ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.business_owner_applications ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.business_images FROM anon, authenticated;
REVOKE ALL ON public.business_owner_applications FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.business_images_id_seq FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.business_owner_applications_id_seq FROM anon, authenticated;

-- Approval/rejection and promotion happen in a single database transaction.
-- Never call this RPC directly from the frontend. The API must first
-- verify JWT + ADMIN role, then use the server secret/service-role client.
CREATE OR REPLACE FUNCTION public.review_business_owner_application(
  p_application_id bigint,
  p_admin_id bigint,
  p_decision text,
  p_admin_note text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_app public.business_owner_applications%ROWTYPE;
  v_admin_role text;
  v_owner_role text;
  v_business_id bigint;
BEGIN
  IF p_decision NOT IN ('APPROVED', 'REJECTED') THEN
    RAISE EXCEPTION 'Decision must be APPROVED or REJECTED' USING ERRCODE = 'B4001';
  END IF;
  IF p_admin_note IS NOT NULL AND char_length(p_admin_note) > 1000 THEN
    RAISE EXCEPTION 'Admin note exceeds 1000 characters' USING ERRCODE = 'B4001';
  END IF;

  SELECT role INTO v_admin_role
  FROM public.users
  WHERE id = p_admin_id AND is_active = true;
  IF v_admin_role IS DISTINCT FROM 'ADMIN' THEN
    RAISE EXCEPTION 'Administrator authorization required' USING ERRCODE = '42501';
  END IF;

  SELECT * INTO v_app
  FROM public.business_owner_applications
  WHERE id = p_application_id
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Application not found' USING ERRCODE = 'B4040';
  END IF;
  IF v_app.status <> 'PENDING' THEN
    RAISE EXCEPTION 'Application already reviewed' USING ERRCODE = 'B4090';
  END IF;

  IF p_decision = 'APPROVED' THEN
    SELECT role INTO v_owner_role
    FROM public.users
    WHERE id = v_app.user_id AND is_active = true
    FOR UPDATE;
    IF v_owner_role IS DISTINCT FROM 'CLIENT' THEN
      RAISE EXCEPTION 'Applicant must be an active CLIENT' USING ERRCODE = 'B4090';
    END IF;

    INSERT INTO public.businesses
      (owner_id, category_id, name, description, address, phone, is_active, logo_path, cover_path)
    VALUES
      (v_app.user_id, v_app.category_id, v_app.business_name,
       v_app.description, v_app.address, v_app.phone, true,
       v_app.logo_path, v_app.cover_path)
    RETURNING id INTO v_business_id;

    UPDATE public.users
    SET role = 'BUSINESS_OWNER'
    WHERE id = v_app.user_id;
  END IF;

  UPDATE public.business_owner_applications
  SET status = p_decision,
      admin_note = p_admin_note,
      reviewed_by = p_admin_id,
      reviewed_at = now(),
      updated_at = now()
  WHERE id = v_app.id;

  RETURN jsonb_build_object(
    'application_id', v_app.id,
    'user_id', v_app.user_id,
    'status', p_decision,
    'business_id', v_business_id
  );
END;
$$;

-- Least privilege for RPC invocation. Backend must use a service-role secret.
REVOKE ALL ON FUNCTION public.review_business_owner_application(bigint,bigint,text,text)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.review_business_owner_application(bigint,bigint,text,text)
  TO service_role;

COMMIT;
